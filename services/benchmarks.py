"""
Loader for verified 10,000-alignment scaling and out-of-range generalization results.

Reads the actual CSV/JSON artifacts generated by `eval_checkpoint.py` and
`train_with_extreme.py` from disk without hardcoding placeholder figures.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

GT_ROOT = Path(__file__).resolve().parents[2]


def _read_csv_rows(path: Path) -> list[list[str]]:
    if not path.exists():
        return []
    with open(path, "r", encoding="utf-8", newline="") as fh:
        return list(csv.reader(fh))


def load_benchmark_summaries() -> dict[str, Any]:
    """Load scaling_results_summary.csv, out_of_range_results_summary.csv, and JSON summaries."""
    scaling_rows = _read_csv_rows(GT_ROOT / "scaling_results_summary.csv")
    extreme_rows = _read_csv_rows(GT_ROOT / "out_of_range_results_summary.csv")

    eval_10k_path = GT_ROOT / "out_N10000" / "eval_summary_N10000.json"
    eval_10k = json.loads(eval_10k_path.read_text(encoding="utf-8")) if eval_10k_path.exists() else {}

    eval_ext_path = GT_ROOT / "out_extreme" / "eval_comparison_before_after.json"
    eval_ext = json.loads(eval_ext_path.read_text(encoding="utf-8")) if eval_ext_path.exists() else {}

    return {
        "scaling_table": {
            "headers": scaling_rows[0] if scaling_rows else [],
            "rows": scaling_rows[1:] if len(scaling_rows) > 1 else [],
        },
        "out_of_range_table": {
            "headers": extreme_rows[0] if extreme_rows else [],
            "rows": extreme_rows[1:] if len(extreme_rows) > 1 else [],
        },
        "eval_10k_summary": eval_10k,
        "eval_extreme_comparison": eval_ext,
    }
